-- MOHAMED FAREED ARENA: initial schema + single-admin RLS
-- Run this in Supabase SQL Editor after creating the Supabase project.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null,
  short_name text,
  badge_emoji text default '⚽',
  created_at timestamptz not null default now()
);

create table if not exists public.players (
  id bigint generated by default as identity primary key,
  team_id bigint references public.teams(id) on delete set null,
  name text not null,
  shirt_number integer,
  position text,
  is_substitute boolean not null default false,
  photo_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  round_number integer not null check (round_number between 1 and 10),
  home_team_id bigint not null references public.teams(id),
  away_team_id bigint not null references public.teams(id),
  kickoff_at timestamptz,
  venue text,
  status text not null default 'upcoming' check (status in ('upcoming','live','finished')),
  home_score integer,
  away_score integer,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  check (home_team_id <> away_team_id)
);

create table if not exists public.player_match_stats (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  goals integer not null default 0 check (goals >= 0),
  assists integer not null default 0 check (assists >= 0),
  rating numeric(3,1) check (rating between 0 and 10),
  is_man_of_match boolean not null default false,
  unique(match_id, player_id)
);

create or replace function public.is_tournament_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid()
  );
$$;

revoke all on function public.is_tournament_admin() from public;
grant execute on function public.is_tournament_admin() to anon, authenticated;

alter table public.admin_users enable row level security;
alter table public.teams enable row level security;
alter table public.players enable row level security;
alter table public.matches enable row level security;
alter table public.player_match_stats enable row level security;

-- Public can read tournament information; only the registered admin can write.
drop policy if exists "admin can view own admin row" on public.admin_users;
create policy "admin can view own admin row" on public.admin_users
for select to authenticated using (user_id = auth.uid());

drop policy if exists "public read teams" on public.teams;
create policy "public read teams" on public.teams
for select to anon, authenticated using (true);
drop policy if exists "admin manage teams" on public.teams;
create policy "admin manage teams" on public.teams
for all to authenticated using (public.is_tournament_admin())
with check (public.is_tournament_admin());

drop policy if exists "public read players" on public.players;
create policy "public read players" on public.players
for select to anon, authenticated using (true);
drop policy if exists "admin manage players" on public.players;
create policy "admin manage players" on public.players
for all to authenticated using (public.is_tournament_admin())
with check (public.is_tournament_admin());

drop policy if exists "public read published matches" on public.matches;
create policy "public read published matches" on public.matches
for select to anon, authenticated using (is_published = true or public.is_tournament_admin());
drop policy if exists "admin manage matches" on public.matches;
create policy "admin manage matches" on public.matches
for all to authenticated using (public.is_tournament_admin())
with check (public.is_tournament_admin());

drop policy if exists "public read stats" on public.player_match_stats;
create policy "public read stats" on public.player_match_stats
for select to anon, authenticated using (true);
drop policy if exists "admin manage stats" on public.player_match_stats;
create policy "admin manage stats" on public.player_match_stats
for all to authenticated using (public.is_tournament_admin())
with check (public.is_tournament_admin());

